"""
Generate an ESPHome configuration that turns an ESP32 into a Bluetooth bridge between
Home Assistant and a Furby Connect, with one button per item of a fluffkit pack.

Nothing on the Furby is modified: the ESP32 talks to it over BLE like the official app.
Uploading packs still happens from a computer (`fluffkit.py upload`); the ESP32 plays them.

Protocol bytes (bluefluff / PyFluff):
  GeneralPlus write  dab91383-...   play action:  13 00 <input> <index> <subindex> <specific>
                                    antenna:      14 <r> <g> <b>
                                    keepalive:    00 (every 3 s keeps Furby in app mode, quiet)
                                    sensor stream on/off: 20 0d / 20 0e
  GeneralPlus notify dab91382-...   20 xx events, 21 .. sensor status (7 bytes, undecoded)
"""
from __future__ import annotations

import json
import re

SERVICE = "dab91435-b5a1-e29c-b041-bcd562613bde"
GP_WRITE = "dab91383-b5a1-e29c-b041-bcd562613bde"
GP_NOTIFY = "dab91382-b5a1-e29c-b041-bcd562613bde"

EVENTS = {  # 20:xx responses (bluefluff doc/generalplus.md)
    0x01: "naming_mode", 0x04: "app_mode", 0x06: "response_played", 0x07: "speech_playing",
    0x0C: "sequence_playing", 0x0D: "sequence_cancelled", 0x0E: "sequence_ended",
    0x13: "sleep_mask_on", 0x14: "sleep_mask_off", 0x17: "eyes_on", 0x18: "eyes_off",
}


def _q(s: str) -> str:
    """Double-quoted YAML string."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _slug(s: str, n: int = 40) -> str:
    s = re.sub(r"\s+", " ", s).strip()
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def generate(mapping: dict, mac: str, name: str = "furby", board: str = "esp32-s3-devkitc-1") -> str:
    if not re.fullmatch(r"([0-9A-Fa-f]{2}:){5}[0-9A-Fa-f]{2}", mac):
        raise ValueError(f"bad MAC address: {mac}")
    if not re.fullmatch(r"[a-z0-9-]{1,31}", name):
        raise ValueError("device name: lowercase letters, digits and '-' only")
    items = sorted(mapping.items(), key=lambda kv: int(kv[0]))
    for _, m in items:
        a = m["action"]
        if len(a) != 4 or not all(0 <= v <= 255 for v in a):
            raise ValueError(f"bad action code: {a}")
    table = ", ".join("{%d, %d, %d, %d}" % tuple(m["action"]) for _, m in items)
    events = "\n".join(f"              case 0x{k:02X}: ev = \"{v}\"; break;" for k, v in EVENTS.items())

    buttons = []
    for k, m in items:
        a = m["action"]
        buttons.append(f"""  - platform: template
    name: {_q(f"Say {k}: {_slug(m['text'])}")}
    icon: mdi:account-voice
    on_press:
      - script.execute: {{id: furby_play, a: {a[0]}, b: {a[1]}, c: {a[2]}, d: {a[3]}}}""")
    buttons_yaml = "\n".join(buttons)

    return f"""# Generated by fluffkit (https://github.com/taituo/fluffkit) - Furby Connect BLE bridge.
# Furby itself is not modified. Upload packs from a computer; this ESP32 plays them.
# Items: {len(items)}. Regenerate after every new pack: fluffkit.py esphome pack.json --mac {mac}

esphome:
  name: {name}
  friendly_name: Furby

esp32:
  board: {board}
  framework:
    type: esp-idf

logger:
api:
  actions:
    - action: say                     # Home Assistant: esphome.{name.replace('-', '_')}_say  item: 3
      variables: {{item: int}}
      then:
        - lambda: |-
            static const uint8_t T[][4] = {{{table}}};
            const int n = sizeof(T) / sizeof(T[0]);
            if (item < 1 || item > n) {{ ESP_LOGW("furby", "no item %d", item); return; }}
            id(furby_play).execute(T[item - 1][0], T[item - 1][1], T[item - 1][2], T[item - 1][3]);
    - action: action                  # any Furby action code: inp/idx/sub/spec (e.g. firmware reactions)
      variables: {{inp: int, idx: int, sub: int, spec: int}}
      then:
        - script.execute: {{id: furby_play, a: !lambda "return inp;", b: !lambda "return idx;", c: !lambda "return sub;", d: !lambda "return spec;"}}
    - action: antenna
      variables: {{r: int, g: int, b: int}}
      then:
        - ble_client.ble_write:
            id: furby
            service_uuid: {SERVICE}
            characteristic_uuid: {GP_WRITE}
            value: !lambda 'return std::vector<uint8_t>{{0x14, (uint8_t) r, (uint8_t) g, (uint8_t) b}};'
    - action: send_hex                # raw GeneralPlus bytes, e.g. "2401"
      variables: {{hex: string}}
      then:
        - ble_client.ble_write:
            id: furby
            service_uuid: {SERVICE}
            characteristic_uuid: {GP_WRITE}
            value: !lambda |-
              std::vector<uint8_t> v;
              for (size_t i = 0; i + 1 < hex.size() && v.size() < 20; i += 2)
                v.push_back((uint8_t) strtol(hex.substr(i, 2).c_str(), nullptr, 16));
              return v;
ota:
  - platform: esphome

wifi:
  ssid: !secret wifi_ssid
  password: !secret wifi_password

esp32_ble_tracker:

ble_client:
  - mac_address: {mac.upper()}
    id: furby
    auto_connect: true
    on_connect:
      - globals.set: {{id: furby_up, value: 'true'}}
      - ble_client.ble_write:
          id: furby
          service_uuid: {SERVICE}
          characteristic_uuid: {GP_WRITE}
          value: [0x14, 0x00, 0xFF, 0x00]      # antenna green = bridge connected
    on_disconnect:
      - globals.set: {{id: furby_up, value: 'false'}}

globals:
  - id: furby_up
    type: bool
    initial_value: 'false'

script:
  - id: furby_play
    parameters: {{a: int, b: int, c: int, d: int}}
    mode: queued
    then:
      - ble_client.ble_write:
          id: furby
          service_uuid: {SERVICE}
          characteristic_uuid: {GP_WRITE}
          value: !lambda 'return std::vector<uint8_t>{{0x13, 0x00, (uint8_t) a, (uint8_t) b, (uint8_t) c, (uint8_t) d}};'

switch:
  - platform: template
    name: "Hold in app mode"           # keepalive: Furby stays quiet and waits for commands
    id: hold
    optimistic: true
    restore_mode: RESTORE_DEFAULT_ON
    icon: mdi:hand-back-left

interval:
  - interval: 3s
    then:
      - if:
          condition:
            lambda: 'return id(furby_up) && id(hold).state;'
          then:
            - ble_client.ble_write:
                id: furby
                service_uuid: {SERVICE}
                characteristic_uuid: {GP_WRITE}
                value: [0x00]

binary_sensor:
  - platform: template
    name: "Connected"
    device_class: connectivity
    lambda: 'return id(furby_up);'

text_sensor:
  - platform: template
    name: "Event"                      # sequence_playing / sequence_ended / sleep_mask_on ...
    id: furby_event
  - platform: template
    name: "Sensor data"                # raw 0x21 status (7 bytes, not decoded yet)
    id: furby_sensor
  - platform: ble_client
    ble_client_id: furby
    id: furby_gp
    internal: true
    service_uuid: {SERVICE}
    characteristic_uuid: {GP_NOTIFY}
    notify: true
    update_interval: never
    on_notify:
      then:
        - lambda: |-
            if (x.empty()) return;
            const uint8_t t = (uint8_t) x[0];
            if (t == 0x20 && x.size() > 1) {{
              const char *ev = nullptr;
              switch ((uint8_t) x[1]) {{
{events}
                default: break;
              }}
              if (ev) id(furby_event).publish_state(ev);
            }} else if (t == 0x21) {{
              char buf[3 * 20 + 1] = {{0}};
              for (size_t i = 0; i < x.size() && i < 20; i++) snprintf(buf + 2 * i, 3, "%02x", (uint8_t) x[i]);
              id(furby_sensor).publish_state(buf);
            }}

button:
  - platform: template
    name: "Sensor stream on"
    on_press:
      - ble_client.ble_write: {{id: furby, service_uuid: {SERVICE}, characteristic_uuid: {GP_WRITE}, value: [0x20, 0x0D]}}
  - platform: template
    name: "Sensor stream off"
    on_press:
      - ble_client.ble_write: {{id: furby, service_uuid: {SERVICE}, characteristic_uuid: {GP_WRITE}, value: [0x20, 0x0E]}}
{buttons_yaml}
"""


def from_map_file(path: str, mac: str, name: str, board: str) -> str:
    with open(path, encoding="utf-8") as f:
        return generate(json.load(f), mac, name, board)
